#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════════
#  deploy.sh — выложить игру: сначала в GitHub, потом на сервер
# ═══════════════════════════════════════════════════════════════════════════
#
#   bash dev/deploy.sh
#
# ── почему сначала GitHub ──────────────────────────────────────────────────
# Раньше этот скрипт брал рабочую копию и клал её на сервер. Полтора года и
# 1305 коммитов живая игра существовала ровно в двух местах — на одном
# компьютере и на дроплете, — и GitHub не знал о ней ничего. Умирает диск —
# умирает проект.
#
# Теперь порядок обратный и он важен: коммит уезжает в GitHub, и только если
# это удалось, сервер выкладывает ИМЕННО ЕГО. Выложить то, чего нет в
# репозитории, стало невозможно — не по договорённости, а механически.
#
# ── и почему сервер тянет сам, а не принимает архив ────────────────────────
# Выкладка больше не привязана к этой машине. Всё, что делает этот скрипт,
# можно сделать и так:
#
#   ssh root@178.128.136.68 'bash /srv/liberty/deploy.sh'
#
# Один источник, одна процедура, два входа.
set -euo pipefail

HOST="${LIBERTY_HOST:-root@178.128.136.68}"
KEY="${LIBERTY_KEY:-$HOME/.ssh/liberty_do}"
REMOTE="${LIBERTY_REMOTE:-libmmo}"
BRANCH=$(git rev-parse --abbrev-ref HEAD)
SSH=(ssh -i "$KEY" -o BatchMode=yes "$HOST")

COMMIT=$(git rev-parse --short HEAD)
DIRTY=$(git status --porcelain | wc -l)
if [ "$DIRTY" -ne 0 ]; then
  echo "  ⚠  $DIRTY незакомічених файлів — деплоїться те, що в комміті," >&2
  echo "     а не те, що в робочій копії. Закоміть спершу." >&2
  exit 1
fi

# ── 1. в GitHub ────────────────────────────────────────────────────────────
# Не удалось — не выкладываем. Иначе на сервере окажется код, которого нет
# больше нигде, и мы вернёмся ровно туда, откуда ушли.
echo "  выгружаю $COMMIT в GitHub ..."
if ! git push --quiet "$REMOTE" "$BRANCH"; then
  echo "  ✗ не смог выгрузить в GitHub — выкладка отменена." >&2
  echo "    Выложить код, которого нет в репозитории, значит снова развести" >&2
  echo "    живую игру и репозиторий. Разберитесь с push и повторите." >&2
  exit 1
fi

# ── 2. довезти коммит до сервера ───────────────────────────────────────────
# Сервер умеет забирать сам (git fetch по ключу доступа), но пока ключ не
# вставлен — или если GitHub недоступен — коммит едет напрямую по ssh. Оба
# пути ведут к одному и тому же объекту: он уже в GitHub, шаг 1 это обеспечил.
echo "  довожу коммит до сервера ..."
GIT_SSH_COMMAND="ssh -i $KEY -o BatchMode=yes" \
  git push --quiet "ssh://$HOST/srv/liberty/repo.git" "$BRANCH" || true

# ── 3. свежий экземпляр процедуры выкладки ─────────────────────────────────
# Канонический экземпляр — в репозитории. Кладём его на сервер каждый раз,
# чтобы серверная копия не начала жить своей жизнью.
scp -i "$KEY" -o BatchMode=yes -q dev/server-deploy.sh "$HOST:/srv/liberty/deploy.sh"
"${SSH[@]}" 'chmod +x /srv/liberty/deploy.sh'

# ── 4. pgtest, на котором гоняются проверки ────────────────────────────────
# Проверки на дроплете запускаются из /srv/liberty/pgtest. Если его не
# обновлять, они проверяют вчерашний код и говорят «всё хорошо» про то, чего
# на сервере уже нет.
echo "  обновляю pgtest (на нём гоняются проверки) ..."
bash "$(dirname "${BASH_SOURCE[0]}")/sync.sh" >/dev/null

# ── 5. холостой прогон ─────────────────────────────────────────────────────
# Собирается ли клиент, раскладывается ли дерево, на месте ли симлинки —
# всё это выясняется ДО перезапуска, то есть не выгоняя игроков.
echo "  проверяю выкладку вхолостую ..."
"${SSH[@]}" "bash /srv/liberty/deploy.sh --dry-run $COMMIT"

# ── 6. и собственно выкладка ───────────────────────────────────────────────
echo "  выкладываю ..."
"${SSH[@]}" "bash /srv/liberty/deploy.sh $COMMIT"
