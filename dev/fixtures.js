'use strict';
// ── Прибирання фікстур, яке не бреше реєстру ───────────────────────────────
//
// Кожен детектор наприкінці зносить свої предмети, і майже всі робили це так:
//
//   DELETE FROM player_items WHERE player_id = ANY($1)
//
// Предмети при цьому ВИДАВАЛИСЬ через items.add — тобто в item_ledger лежав
// запис «+150 sw1», а рядків не лишалось. Для звірки це рівно те, що вона
// існує ловити: предмети зникли в обхід repos/items.js.
//
// І вона зловила. 27 серпня о 05:23 в топік алертів прийшло «Расхождение
// предметов и журнала: 216 пар», і всі до одної — тестові акаунти, здебільшого
// «на руках 0, журнал 150»: це `for (i < SERVER_INV_MAX) items.add(…'sw1')` з
// consumables-check і progression-check, знесене сирим DELETE.
//
// Прибрати фікстуру повністю не можна: у ledger.player_id зовнішній ключ без
// ON DELETE, а DELETE на ledger у застосунку відкликано — тому рядок гравця
// переживає будь-яке прибирання (це й є причина, чому їх накопичилось три з
// половиною тисячі). Отже єдине, що можна зробити чесно, — зносити предмети
// ТИМИ Ж ДВЕРИМА, якими їх видали, щоб сума дельт зійшлася в нуль.
//
// Ціна — один DELETE на рядок замість одного на гравця. Це прибирання тесту,
// не гарячий шлях, і платити тут секундою краще, ніж щоночі будити людину
// тривогою, яка через тиждень перестане щось означати.
const { tx, query } = require('../server/db');
const items = require('../server/db/repos/items');

// Знімає всі предмети гравця так, як це зробив би сам застосунок.
//
// Повертає, скільки рядків знято — детектор може це перевірити, а не вірити.
async function wipeItems(playerId) {
  const id = Number(playerId);
  if (!Number.isFinite(id)) return 0;
  return tx(async (t) => {
    await items.lockPlayer(t, id);
    // Разом з екіпіруванням і сховищем: container тут не важливий, важливо, що
    // рядок належить гравцеві. Ті, що поїхали на ринок, мають player_id NULL і
    // сюди не потрапляють — їх знімає окреме прибирання лотів у market-check.
    const { rows } = await query(t,
      'SELECT id FROM player_items WHERE player_id = $1 ORDER BY id', [id]);
    let n = 0;
    for (const r of rows) {
      // reason: 'test_teardown' — навмисно окреме слово. Якщо ці записи колись
      // побачать у живому реєстрі, має бути одразу видно, що це прибирання
      // тесту, а не рух у грі.
      if (await items.removeRow(t, Number(r.id), id, { reason: 'test_teardown' })) n++;
    }
    return n;
  });
}

// Те саме для списку гравців. Кожен у власній транзакції: одна фікстура, яку
// не вдалося прибрати (наприклад, її предмет тримає активний лот), не має
// забирати з собою прибирання решти.
async function wipeItemsAll(playerIds) {
  let n = 0;
  for (const id of (playerIds || [])) {
    try { n += await wipeItems(id); }
    catch (err) { console.error(`  fixtures: не прибрав предмети гравця ${id}: ${err.message}`); }
  }
  return n;
}

module.exports = { wipeItems, wipeItemsAll };
