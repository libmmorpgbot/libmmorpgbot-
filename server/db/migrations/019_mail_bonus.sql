-- ── Письмо: второй бесплатный набор, и он тоже раз на аккаунт ─────────────
--
-- Кнопка «Письмо» в колонке HUD выдаёт одну из двух наград — какую именно,
-- решает сезонный билет (MAIL_BONUS, shared/definitions.js). Награды две,
-- а забрать можно одну: у владельца билета своя, у всех остальных своя.
--
-- Отдельная колонка, а не переиспользование starter_bonus_claimed: это разные
-- награды, и аккаунт, забравший набор новичка, письмо ещё не получал. Общий
-- флаг молча лишил бы письма всех, кто играет не первый день, — то есть почти
-- всех, кому оно и предназначено.
--
-- NOT NULL DEFAULT false: у всех существующих строк письмо не забрано, и это
-- ровно то, что нужно — иначе награду не увидел бы никто, кроме новых
-- аккаунтов. Postgres 11+ пишет такой DEFAULT в каталог, а не переписывает
-- таблицу, так что ALTER не блокирует player_progress на время выкладки.
--
-- IF NOT EXISTS — потому что migrate.sh идемпотентен по файлу, но повторный
-- прогон после ручного вмешательства в базу не должен падать на «колонка уже
-- есть».
ALTER TABLE player_progress
  ADD COLUMN IF NOT EXISTS mail_bonus_claimed boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN player_progress.mail_bonus_claimed IS
  'Письмо получено: одна из двух наград MAIL_BONUS, один раз на аккаунт';
