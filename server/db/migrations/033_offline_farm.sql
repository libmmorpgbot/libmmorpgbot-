-- ── Оффлайн-фарм ────────────────────────────────────────────────────────────
--
-- Игрок выбирает локацию и выходит из игры; при следующем входе сервер
-- считает, сколько он успел бы там нафармить, и выдаёт награду
-- (server/offline-farm.js).
--
-- Одна колонка на игрока, а не своя таблица: запущенный фарм у игрока может
-- быть только один, а забирается он в той же транзакции, что и награда, — та
-- же строка player_progress, которую награда всё равно блокирует (grantXp).
--
--   NULL                  фарма нет
--   {"loc", "at", "st"}   локация, момент запуска (мс) и снимок боевых
--                         характеристик на этот момент — без временных зелий,
--                         чтобы банка атаки перед выходом не множила 12 часов.
ALTER TABLE player_progress
  ADD COLUMN IF NOT EXISTS offline_farm jsonb;
