-- ── Руны: содержимое предмета и гнёзда ─────────────────────────────────────
--
-- Руна — первая вещь в игре, у которой содержимое СВОЁ у каждого экземпляра.
-- До сих пор строка player_items полностью описывалась каталогом: item_id
-- говорил, ЧТО это, enhance — насколько заточено, и всё. Две эпические руны
-- доспеха — это два разных набора характеристик, и различает их только то,
-- что выпало при ковке.
--
-- Три решения, каждое из которых можно было принять иначе.
--
-- 1. ОТДЕЛЬНОЙ ТАБЛИЦЫ НЕТ. Руна лежит в player_items, как любая другая вещь,
--    и получает даром всё, что уже вокруг неё построено: место в инвентаре,
--    журнал предметов (item_ledger, 012), провенанс (source/source_ref, 011),
--    рынок (лот — это строка с player_id = NULL, 010) и каскадное удаление
--    вместе с аккаунтом. Своя таблица означала бы повторить каждое из этого
--    заново — и забыть половину.
--
-- 2. jsonb, А НЕ КОЛОНКИ. Характеристики руны — список переменной длины (от
--    одной до пяти), и каждая строка это пара «какая» + «какого цвета».
--    Разложить это по колонкам значит завести десять полей, девять из которых
--    у обычной руны пустые. Схема здесь ничего не проверяет намеренно: что
--    бывает допустимым набором, решает shared/definitions.js (RUNE_*), один
--    файл на клиент и сервер, и дублировать те же правила в CHECK означало бы
--    два места, которые разойдутся.
--
-- 3. ГНЕЗДО — ЭТО ССЫЛКА РУНЫ НА ПРЕДМЕТ, а не список рун внутри предмета.
--    Так вставленная руна остаётся обычной строкой: у неё есть владелец, своя
--    история в журнале, её можно вынуть одним UPDATE. Обратный вариант —
--    массив id внутри предмета — сделал бы руну в гнезде вещью, которой нет
--    в player_items, то есть невидимой и для журнала, и для сверки.
--
-- Вставленная руна НЕ ЗАНИМАЕТ места в инвентаре: она лежит в контейнере
-- 'inventory' (иначе не выполнится player_items_owned_ck), но каждый запрос,
-- который считает слоты или показывает сумку, отсекает socket_of IS NOT NULL
-- (см. usedSlots/inventoryOf, server/db/repos/items.js).

ALTER TABLE player_items ADD COLUMN IF NOT EXISTS rune jsonb;

-- Хозяин гнезда. ON DELETE CASCADE: предмет уничтожен — руны в нём исчезают
-- вместе с ним. Это не потеря данных исподтишка, а причина, по которой
-- продажа и выброс предмета с рунами запрещены в коде (см. repos/runes.js):
-- каскад здесь — последняя защита от висящей ссылки, а не обычный путь.
ALTER TABLE player_items ADD COLUMN IF NOT EXISTS socket_of  bigint
  REFERENCES player_items(id) ON DELETE CASCADE;
ALTER TABLE player_items ADD COLUMN IF NOT EXISTS socket_idx smallint;

-- Либо руна в гнезде (хозяин и номер), либо нет. Половины не бывает: строка
-- с socket_of без номера не имеет места, куда её рисовать, а с номером без
-- хозяина — предмета, которому она принадлежит.
DO $ck$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'player_items_socket_ck'
       AND conrelid = 'player_items'::regclass
  ) THEN
    ALTER TABLE player_items ADD CONSTRAINT player_items_socket_ck
      CHECK ((socket_of IS NULL) = (socket_idx IS NULL));
  END IF;
END
$ck$;

-- Одно гнездо — одна руна. Без этого две параллельные вставки в третье гнездо
-- шлема обе прошли бы, и предмет молча получил бы четыре руны в трёх гнёздах.
CREATE UNIQUE INDEX IF NOT EXISTS player_items_socket_key
  ON player_items (socket_of, socket_idx) WHERE socket_of IS NOT NULL;

-- Путь доступа «покажи руны этого предмета» — он нужен на каждом пересчёте
-- характеристик и на каждой отрисовке карточки.
CREATE INDEX IF NOT EXISTS player_items_socket_host_idx
  ON player_items (socket_of) WHERE socket_of IS NOT NULL;

-- Права не выдаются заново намеренно: колонки наследуют права таблицы, а
-- liberty_app уже имеет на player_items SELECT/INSERT/UPDATE/DELETE
-- (server/db/migrate.sh). Ни CREATE на схеме, ни владения таблицей у него
-- по-прежнему нет.
