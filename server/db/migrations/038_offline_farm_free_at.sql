-- ── Оффлайн-фарм: перезарядка бесплатного часа ─────────────────────────────
--
-- Без сезонного билета засчитывается один час (OFFLINE_FARM_FREE_HOURS), но
-- запустить его можно не чаще раза в OFFLINE_FARM_FREE_COOLDOWN_HOURS
-- (shared/definitions.js). Иначе после часа фарм ставят снова, и так по кругу.
--
-- Отдельная колонка, а не поле offline_farm: та обнуляется при выдаче, а
-- момент последнего бесплатного запуска должен её пережить.
--
--   NULL   бесплатным часом ещё не пользовались
--   число  момент последнего бесплатного запуска, мс
ALTER TABLE player_progress
  ADD COLUMN IF NOT EXISTS offline_farm_free_at bigint;
