-- ── Срез очков клана до 800 000 ─────────────────────────────────────────────
--
-- Раньше 10-й уровень был последним (800 000 очков), и опыт за убийства
-- копился сверх него. Теперь над ним уровни 11–15 (от 1 100 000), и клан с
-- накопленным «лишним» опытом сразу перескочил бы на них. По решению
-- владельца каждый клан остаётся на своём уровне: всё, что выше 800 000,
-- срезается до порога 10-го уровня. Дальше клан растёт только
-- пожертвованиями.
--
-- Разовая: migrate.sh применяет файл один раз. Катится в той же выкладке,
-- что и пожертвования (042), и ДО перезапуска — так что срезается только
-- опыт за убийства, а не пожертвованное.
UPDATE clans SET xp = 800000, level = 10 WHERE xp > 800000;
