-- ── Ключ идемпотентности не должен переживать сброс ────────────────────────
--
-- Два подтверждённых эксплойта одной формы. Оба стоят на том, что `ledger`
-- APPEND-ONLY (см. REVOKE в migrate.sh), а idem_key в нём UNIQUE: ключ,
-- который однажды лёг в таблицу, лежит там навсегда. Значит ключ, собранный
-- из состояния, которое игрок может ВЕРНУТЬ НАЗАД, — это выданное навсегда
-- разрешение купить то же самое ещё раз и не заплатить.
--
-- ── 1. Улучшения характеристик ────────────────────────────────────────────
--
-- spendUpgrade собирал ключ `upg:<pid>:<стат>:<текущий уровень стата>`, а
-- resetUpgrades возвращал все семь колонок upg_* в 0. После сброса покупка
-- atk снова давала `upg:<pid>:atk:0` — ключ, который в ledger уже есть, — и
-- money.spend уходил в ветку replay. Она возвращает { balance, replayed:true },
-- то есть ИСТИНУ, поэтому `if (!paid) return null;` её пропускал: очко
-- выдавалось, не списав ни монеты. Воспроизведено на живой схеме:
--
--   куплено 3 очка atk:      золото 100000 → 98200  (списано 1800)
--   после сброса:            золото 98200
--   куплено 3 очка ПОВТОРНО: золото 98200 → 98200  (списано 0), upg_atk = 3
--
-- Ночная сверка money.reconcile() этого не видела и не могла увидеть: по ветке
-- replay не пишется НИЧЕГО, так что баланс и сумма ledger продолжают
-- сходиться до копейки. Единственный свидетель — золото, которое не
-- уменьшилось.
--
-- ── 2. Создание клана ─────────────────────────────────────────────────────
--
-- То же самое, дешевле: ключ был `clan_create:<pid>:<имя>`, а disband делает
-- DELETE FROM clans и освобождает имя (clans.name — citext UNIQUE). «Alpha» →
-- распустить → «Alpha» снова = клан за 0 вместо CLAN_CREATE_COST.
--
-- ── почему счётчик, а не случайное значение ────────────────────────────────
--
-- Ключ обязан быть ОДНИМ И ТЕМ ЖЕ у двух попыток одной операции и РАЗНЫМ у
-- двух разных действий игрока. Первое — это буквально то, ради чего ключ
-- существует: txRetry повторяет весь обработчик после отката (40001/40P01), и
-- вторая попытка должна опознаться как та же самая. Math.random(),
-- randomUUID() и Date.now() ломают именно первое свойство — повтор получил бы
-- другой ключ, и защиты не осталось бы вовсе. Это те самые примеры, которые
-- repos/money.js в своём списке помечает как «bad».
--
-- Монотонный счётчик даёт оба свойства сразу. Он читается ПОД ТЕМ ЖЕ row
-- lock, что и вся остальная операция, поэтому повтор после отката видит то же
-- значение (откат вернул и счётчик тоже), а следующее действие игрока видит
-- уже другое — предыдущее увеличило его в той же транзакции, которая его
-- потратила. Ни одного лишнего чтения времени, случайности или внешнего
-- состояния: всё в той же строке, под тем же локом.
--
-- ── почему бэкфилл не нужен ────────────────────────────────────────────────
--
-- Обе колонки стартуют с 0 у всех, включая тех, кто уже покупал улучшения и
-- основывал кланы. Это безопасно, потому что НОВЫЙ формат ключа доказуемо не
-- пересекается со старым, а не потому, что мы надеемся на разные значения:
--
--   было  `upg:<pid>:<стат>:<уровень>`        ровно 4 сегмента, последний —
--                                             десятичное число
--   стало `upg:<pid>:<стат>:e<эпоха>:<уровень>` 5 сегментов, и `e0` не число
--
--   было  `clan_create:<pid>:<имя>`           сегмент 2 — десятичный pid
--   стало `clan_create:e<эпоха>:<pid>:<имя>`  сегмент 2 — `e<число>`
--
--   было  `upgrade_reset:<pid>:<uuid>`        36 символов с дефисами
--   стало `upgrade_reset:<pid>:e<эпоха>`      `e` и цифры, дефисов нет
--
-- Маркер `e` стоит там, где он стоит, не для красоты. У КЛАНОВ имя приходит
-- от игрока и проверяется только по длине (1..10) — двоеточие в нём никто не
-- запрещал. Поставь эпоху рядом с именем, и клан, названный когда-то «0:alpha»,
-- дал бы старый ключ `clan_create:<pid>:0:alpha`, в точности равный новому
-- ключу для клана «alpha» в эпоху 0. Сегмент перед pid — единственное место,
-- куда имя дотянуться не может, потому что там всегда стоял десятичный pid.
--
-- Практический смысл: сразу после миграции первая покупка и первое создание
-- клана списывают деньги у КАЖДОГО, включая тех, кто успел воспользоваться
-- дырой. Старые ключи остаются в ledger как история и больше никогда никому
-- ничего не открывают.

-- Счётчик сбросов улучшений. Растёт на 1 в том же UPDATE, который обнуляет
-- семь колонок upg_* (repos/players.js resetUpgrades) — одним оператором, а не
-- рядом с ним, чтобы «обнулили, но не увеличили» не существовало как
-- состояние даже на время одного оператора.
--
-- NOT NULL DEFAULT 0 не переписывает таблицу: с PostgreSQL 11 значение по
-- умолчанию для добавляемой колонки хранится в каталоге, так что это операция
-- над метаданными и окно обслуживания под неё не нужно.
ALTER TABLE player_progress
  ADD COLUMN IF NOT EXISTS upg_epoch integer NOT NULL DEFAULT 0
    CHECK (upg_epoch >= 0);

COMMENT ON COLUMN player_progress.upg_epoch IS
  'сколько раз улучшения сбрасывали. Единственное назначение — входить в idem_key покупки очка, чтобы ключ не повторился после обнуления upg_* колонок. Только растёт';

-- Счётчик ОСНОВАННЫХ кланов, а не распущенных: эпоху тратит каждое успешное
-- создание, поэтому два создания одним игроком не могут дать один ключ ни при
-- каком порядке роспусков, выходов и переименований. Считать роспуски было бы
-- тоньше и хуже: клан можно покинуть, можно быть из него исключённым, и не
-- каждый способ освободить имя проходит через disband.
--
-- Живёт на `players`, а не на `player_progress`: основание клана — факт об
-- АККАУНТЕ, как can_message (013) и ton_address (015), и читается ровно на том
-- же locked-строке, которую clans.create уже держит через items.lockPlayer.
-- Четыре байта на строку, которая и без того читается на каждом логине, —
-- цена, которую эта таблица уже платила дважды.
ALTER TABLE players
  ADD COLUMN IF NOT EXISTS clan_epoch integer NOT NULL DEFAULT 0
    CHECK (clan_epoch >= 0);

COMMENT ON COLUMN players.clan_epoch IS
  'сколько кланов этот аккаунт основал. Входит в idem_key оплаты создания, чтобы «создать → распустить → создать то же имя» не попадало в ветку replay. Только растёт';
