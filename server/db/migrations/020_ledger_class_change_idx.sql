-- ── Вход перестал упираться в полное чтение журнала денег ──────────────────
--
-- Симптом: «canceling statement due to statement timeout» и игроки не могут
-- зайти в игру. Таймаут у нас 5 секунд (PG_STATEMENT_TIMEOUT_MS,
-- server/db/index.js), то есть запрос не сломался, а не дождался.
--
-- Виновник — одна строка в сборке savedData (server/session.js), которая
-- выполняется НА КАЖДОМ ВХОДЕ:
--
--   SELECT count(*) FROM ledger WHERE player_id = $1 AND reason = 'class_change'
--
-- Считается ради мелочи: доступна ли игроку ещё первая смена класса за
-- Liberty. Платится за это чтением ВСЕЙ таблицы.
--
-- Почему существующий ledger_player_idx (player_id, currency, id DESC) не
-- спасает: у активного игрока движений денег — половина таблицы (каждое
-- убийство монстра это строка), и планировщик справедливо решает, что
-- последовательный скан дешевле индексного. Замерено на копии схемы,
-- 1.6 млн строк / 304 МБ, холодный кэш:
--
--   без индекса   Parallel Seq Scan, 17743 страницы, 200 мс
--   с индексом    Index Only Scan,   5 страниц,      0.49 мс
--
-- Разница в 400 раз, и она растёт: скан дорожает вместе со ВСЕЙ таблицей, а
-- журнал append-only и не уменьшается никогда. Индекс частичный — в нём
-- только строки смены класса, которых у игрока ноль-два. 16 КБ на всю базу.
--
-- ── ВНИМАНИЕ ПРИ НАКАТЕ НА ЖИВУЮ БАЗУ ──────────────────────────────────────
-- Здесь обычный CREATE INDEX, и он берёт на ledger блокировку SHARE: запись в
-- журнал встаёт на всё время построения. На пустой базе это мгновенно, на
-- боевой — секунды или минуты, в течение которых КАЖДОЕ движение денег в игре
-- упрётся в тот же пятисекундный таймаут. То есть лечение выглядело бы как
-- болезнь.
--
-- Поэтому на боевой базе индекс строится ОТДЕЛЬНО и БЕЗ блокировки:
--
--   bash dev/index-now.sh
--
-- CONCURRENTLY нельзя положить сюда: migrate.sh гоняет файлы через
-- --single-transaction, а такой индекс внутри транзакции не создаётся. После
-- index-now.sh эта миграция находит индекс на месте и не делает ничего —
-- ровно для этого здесь IF NOT EXISTS.
CREATE INDEX IF NOT EXISTS ledger_class_change_idx
  ON ledger (player_id) WHERE reason = 'class_change';
