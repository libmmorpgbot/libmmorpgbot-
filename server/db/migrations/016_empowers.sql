-- ── Перерождение стало Усилением: тот же счётчик, другое имя ───────────────
--
-- Перерождение сбрасывало уровень до 1 и выдавало +15 очков навыка. Усиление
-- выдаёт те же +15 и НИЧЕГО не сбрасывает: уровень, опыт, статы и вложенные
-- улучшения остаются как были. Меняется только цена — она растёт по тирам от
-- номера усиления, и больше тридцати их не бывает.
--
-- Колонка переименована, а не заведена рядом, потому что тальи одна и та же.
-- Игрок, переродившийся четыре раза, находится на четырёх усилениях: его
-- следующее — пятое, и стоит оно по второму тиру. Завести пустой `empowers`
-- рядом со старым `rebirths` значило бы вернуть таких игроков в начало
-- лестницы цен и обнулить им «Усилений пройдено» на панели.
--
-- RENAME, а не «добавить + скопировать + удалить»: переименование не
-- переписывает ни одной строки таблицы и не может потерять значение на
-- полпути. CHECK-ограничение переезжает вместе с колонкой; имя ограничения
-- Postgres оставит прежним (player_progress_rebirths_check), и это не
-- опечатка — переименовывать его отдельно нечего, на поведение оно не влияет.
--
-- Обратной миграции нет и не нужно: старый код читал `rebirths`, новый читает
-- `empowers`, и одновременно на одной базе они не работают. Откат — это
-- обратный RENAME, если такое вообще понадобится.
--
-- Смысл keptSP при этом не меняется: он остаётся полем ТОЛЬКО ДЛЯ ЧТЕНИЯ.
-- Его несут записи тех, кто реально перерождался, и без него их вложенные
-- улучшения не прошли бы потолок очков анти-чита. Усиление в него не пишет —
-- сбрасывать ему нечего.

ALTER TABLE player_progress RENAME COLUMN rebirths TO empowers;
