-- ── Имя в Телеграме не может закрывать вход в игру ─────────────────────────
--
--   [socket:loginTelegramWebApp] error: duplicate key value violates unique
--   constraint "players_username_key"
--
-- Пять раз за неделю, последний — сегодня. Для игрока это выглядит так:
-- «Захожу, грузит, и потом всё чёрное. Просто кнопка портала в зал стоит и
-- всё». Вход падает целиком, транзакция откатывается, сессии нет — а рисовать
-- клиенту нечего.
--
-- Причина: players.username объявлена UNIQUE. Имя берётся из профиля Телеграма
-- (finishLogin → _safeUsername), а имена в Телеграме не уникальны и никогда
-- ими не были. Двое «Максим» — и второй не может войти НИКОГДА: у ensure
-- стоит ON CONFLICT (telegram_id), а нарушается совсем другое ограничение.
-- Тот же капкан ждёт и старого игрока, который переименовался в занятое имя:
-- падает уже setUsername, на каждом входе.
--
-- ── этого ограничения не было в прежней сборке ─────────────────────────────
-- Проверено по F:\a Projects\old_version_liberty_mmorpg:
--
--   PlayerSchema.index({ username: 1 }, { collation: { locale: 'en', strength: 2 } });
--
-- Индекс — да, уникальность — нет. Уникальность появилась при переносе на
-- Postgres и не несёт никакой пользы: единственное место, где имя работает
-- ключом, — поиск получателя личного сообщения, и он и так сравнивает без
-- учёта регистра (lower(username) = lower($1)), тогда как индекс был
-- регистрозависимым. То есть «Вася» и «вася» могли существовать оба, и выбор
-- между ними всё равно был случайным. Ограничение обещало однозначность,
-- которой не давало.
--
-- Поэтому: уникальность снимается, а поиск делается определённым — точное
-- совпадение регистра вперёд, дальше самый старый аккаунт (server/db/repos/
-- chat.js). Индекс остаётся, но по lower(username): именно так его и
-- спрашивают.
ALTER TABLE players DROP CONSTRAINT IF EXISTS players_username_key;
DROP INDEX IF EXISTS players_username_key;

-- Тот самый поиск: WHERE lower(username) = lower($1). Без этого индекса он
-- читает таблицу целиком, а зовут его на каждое «написать @Имя».
CREATE INDEX IF NOT EXISTS players_username_lower_idx ON players (lower(username));

COMMENT ON COLUMN players.username IS
  'отображаемое имя из профиля Телеграма. НЕ уникально и не может быть: имена в Телеграме не уникальны, а уникальность здесь закрывала вход тёзкам (см. миграцию 018). Личность аккаунта — telegram_id';
