-- ── Карма ───────────────────────────────────────────────────────────────────
-- Карма игрока за убийства других игроков в обычных локациях (KARMA_PER_PK,
-- shared/definitions.js). Смывается убийством монстров, обнуляется смертью.
-- Хранится в базе, чтобы перезаход не снимал её: пока карма больше нуля, ПК
-- не выключается и телепорты закрыты (server/karma.js).
--
-- Добавляющая: до неё колонки нет, и карма не копится (hasColumn).
ALTER TABLE player_progress ADD COLUMN IF NOT EXISTS karma integer NOT NULL DEFAULT 0
  CHECK (karma >= 0);
COMMENT ON COLUMN player_progress.karma IS
  'Карма за ПК в локациях; > 0 — ПК не выключить, телепорты закрыты';
