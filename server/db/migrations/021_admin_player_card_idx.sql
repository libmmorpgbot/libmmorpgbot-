-- ── Карточка игрока в админке перестала читать журнал целиком ───────────────
--
-- Симптом: «canceling statement due to statement timeout» при открытии игрока
-- в админ-панели (client.admin:openPlayer). Таймаут 5 секунд
-- (PG_STATEMENT_TIMEOUT_MS, server/db/index.js) — запрос не сломался, а не
-- дождался. Та же болезнь, что лечила миграция 020, только на другом экране.
--
-- Виноваты три запроса в GET /admin/player/:tid (server/routes/admin2.js).
-- Измерено здесь же, на 4.5 млн строк журнала, из них 300 тыс. у одного
-- игрока:
--
--   лента событий      Bitmap Scan: прочитаны ВСЕ 300 898 строк игрока,
--                      отфильтрованы до 898, отсортированы          47 мс
--                      а когда запрос уезжает в generic-план — Index Scan
--                      Backward по pkey с отбросом 1 424 702 строк  285 мс
--   итог по мобам      Parallel Seq Scan ВСЕЙ таблицы               135 мс
--   сезонная лента     Index Scan с отбросом 29 940 строк           3.8 мс
--
-- Важнее самих чисел то, ЧЕМ они растут. Полное чтение дорожает и от чужой
-- игры: журнал append-only и не уменьшается никогда, поэтому чем больше в
-- игре людей, тем медленнее открывается карточка любого из них. На боевой
-- базе это и вышло за пять секунд.
--
-- После индексов ниже:
--
--   лента событий      Index Scan по частичному индексу              0.25 мс
--   итог по мобам      Parallel Index Only Scan, Heap Fetches: 0     24 мс
--   сезонная лента     Index Scan без отбросов                       0.4 мс
--
-- ── почему одних индексов было мало ────────────────────────────────────────
-- Список причин-«шума» приезжал в запрос ПАРАМЕТРОМ ($2, text[]). Частичный
-- индекс планировщик применяет, только если может доказать его предикат из
-- текста запроса, а из bind-параметра он его вывести не может: значение
-- приходит уже после планирования. Индекс существовал бы и не применялся.
-- Поэтому причины переехали в текст запроса константами — см. NOISE_OUT /
-- NOISE_IN / SEASON_EVENT в server/routes/admin2.js. Предикаты здесь и
-- условия там обязаны совпадать; за этим следит dev/adminperf-check.js.
--
-- ── ВНИМАНИЕ ПРИ НАКАТЕ НА ЖИВУЮ БАЗУ ──────────────────────────────────────
-- Здесь обычный CREATE INDEX, и он берёт на ledger блокировку SHARE: запись в
-- журнал встаёт на всё время построения, а на боевом журнале это минуты — и
-- каждое движение денег в игре упрётся в тот же пятисекундный таймаут.
-- Лечение выглядело бы как болезнь.
--
-- Поэтому на боевой базе индексы строятся ОТДЕЛЬНО и БЕЗ блокировки:
--
--   bash dev/migrate-now.sh
--
-- CONCURRENTLY нельзя положить сюда: migrate.sh гоняет файлы через
-- --single-transaction, а такой индекс внутри транзакции не создаётся.
-- migrate-now.sh строит их без блокировки ДО того, как позвать migrate.sh, и
-- эта миграция находит их на месте и не делает ничего — ровно для этого здесь
-- IF NOT EXISTS.

-- Лента событий: всё, КРОМЕ награды за убийства. У активного игрока таких
-- строк сотни на сотни тысяч, поэтому индекс — крохотный (48 КБ на 4.5 млн
-- строк журнала), а порядок (player_id, id DESC) отдаёт последние 80 без
-- сортировки вовсе.
CREATE INDEX IF NOT EXISTS ledger_player_events_idx
  ON ledger (player_id, id DESC)
  WHERE reason <> 'mob_kill' AND reason <> 'mob_drop';

-- Итог «сколько золота пришло с мобов за всё время». Это единственная строка
-- карточки, которой действительно нужны ВСЕ строки игрока, и укоротить её
-- нельзя, не поменяв смысл числа. Зато можно перестать ради неё читать чужие:
-- INCLUDE (delta) кладёт в индекс само слагаемое, и проход становится
-- index-only — без единого обращения к таблице (Heap Fetches: 0).
--
-- Он остаётся линейным по истории ОДНОГО игрока. Если когда-нибудь и этого
-- станет мало, следующий шаг — не индекс, а накопительный итог: считать сумму
-- при записи, а не при чтении.
CREATE INDEX IF NOT EXISTS ledger_player_mobgold_idx
  ON ledger (player_id) INCLUDE (delta)
  WHERE currency = 'gold' AND (reason = 'mob_kill' OR reason = 'mob_drop');

-- Сезонная лента. player_logs секционирована по месяцам, и индекс на
-- родителе разъезжается по всем секциям — включая те, что создаст ежемесячная
-- задача: PostgreSQL заводит совпадающий индекс на каждой новой секции сам.
CREATE INDEX IF NOT EXISTS player_logs_season_idx
  ON player_logs (player_id, created_at DESC)
  WHERE event LIKE 'season%';
