-- ── player_skills.class_override — заимствованная способность ──────────────
--
-- Джекпот легендарного перебора руны (RUNE_REROLL_BONUS_SKILL_CHANCE,
-- shared/definitions.js, 3% на кнопку) выдаёт книгу активного навыка ЛЮБОГО
-- класса. Эта колонка — что происходит, когда её действительно изучают: слот
-- Q/W/E/R получает НАСТОЯЩУЮ способность чужого класса (своя механика боя —
-- урон, АОЕ, рывок, лечение — не число из своей таблицы под чужим именем),
-- а не превращается в книгу своего класса.
--
-- NULL — подавляющее большинство строк: слот способности того класса, что и
-- у игрока. Непустое значение переопределяет ТОЛЬКО ДЛЯ ЭТОЙ СТРОКИ, какой
-- класс отвечает за то, что реально произойдёт при касте этого слота —
-- Room.js читает её как «эффективный класс» вместо charClass везде, где
-- решается механика/урон/дальность этого конкретного слота.
--
-- Только у kind='skill': пассивки и книги второй профессии класс не меняют —
-- вторая профессия слота жёстко привязана к его БАЗОВОЙ способности по ключу
-- (ADV_SKILL_DEF, js/definitions.js), а не к отдельной записи, которую можно
-- было бы переопределить так же. setForeignSkill (repos/players.js) поэтому
-- снимает adv_learned/adv_active этого ключа при каждой смене класса слота —
-- сохранённая «вторая профессия» была книгой для СТАРОЙ способности.
ALTER TABLE player_skills
  ADD COLUMN IF NOT EXISTS class_override char_class_t;

ALTER TABLE player_skills
  DROP CONSTRAINT IF EXISTS player_skills_override_kind_ck;
ALTER TABLE player_skills
  ADD CONSTRAINT player_skills_override_kind_ck
    CHECK (class_override IS NULL OR kind = 'skill');

COMMENT ON COLUMN player_skills.class_override IS
  'Эффективный класс этого Q/W/E/R слота, когда он отличается от charClass игрока — заимствованная способность из джекпота переработки легендарной руны (learnForeignSkill). NULL — обычный случай, слот своего класса.';
