-- ── Письмо: новый состав наград, и он снова раз на аккаунт ────────────────
--
-- Кнопка «Письмо» больше не выдаёт награды из MAIL_BONUS образца миграции
-- 019 — состав в shared/definitions.js заменён целиком (без билета: 5 банок
-- каждого бафа; с билетом: 20 банок каждого бафа, обычные крылья, 3
-- необычных и 3 редких сундука), и это письмо действует до конца 3-го
-- сезона (seasonActive(), claimMailBonus).
--
-- Отдельная колонка, а не переиспользование mail_bonus_claimed: это письмо
-- прямо не связано с прошлым, и тот, кто уже забрал старую награду, обязан
-- увидеть кнопку снова и получить новую. Переиспользованный флаг молча
-- лишил бы письма ровно тех, кто в прошлый раз его не пропустил, — то есть
-- самых активных игроков.
--
-- NOT NULL DEFAULT false: у всех существующих строк новое письмо не
-- забрано, включая тех, у кого mail_bonus_claimed уже true. Postgres 11+
-- пишет такой DEFAULT в каталог, а не переписывает таблицу, так что ALTER
-- не блокирует player_progress на время выкладки.
--
-- IF NOT EXISTS — потому что migrate.sh идемпотентен по файлу, но повторный
-- прогон после ручного вмешательства в базу не должен падать на «колонка уже
-- есть».
ALTER TABLE player_progress
  ADD COLUMN IF NOT EXISTS mail_bonus2_claimed boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN player_progress.mail_bonus2_claimed IS
  'Новое письмо получено: одна из двух наград MAIL_BONUS (состав после миграции 030), один раз на аккаунт, не связано со старым mail_bonus_claimed';
